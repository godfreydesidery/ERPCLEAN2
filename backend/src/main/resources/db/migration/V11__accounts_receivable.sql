-- V11 — Accounts Receivable module (ADR-0014): ar_invoices, ar_receipts,
-- ar_receipt_allocations, ar_credit_notes, ar_write_offs; CoA seed (5500, 3100);
-- gl_configs CHECK widen + BAD_DEBT_EXPENSE / OPENING_BALANCE_EQUITY keys;
-- journal source-type CHECK widen (AR_RECEIPT, AR_WRITEOFF, AR_CREDIT_NOTE);
-- permissions seed + ORG_ADMIN grant.
-- Additive only. V1–V10 are FROZEN.
-- Order per ADR-0014 D-14: ar_invoices → ar_receipts → ar_receipt_allocations →
-- ar_credit_notes → ar_write_offs → indexes → CoA seed → gl_configs → source-type →
-- permission seed.

-- ============================================================================
-- (1) ar_invoices — the open items (the sub-ledger detail behind GL 1200)
-- ============================================================================
CREATE TABLE ar_invoices (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                  VARCHAR(26)     NOT NULL,
    company_id           BIGINT          NOT NULL,
    branch_id            BIGINT,
    customer_id          BIGINT          NOT NULL,
    source               VARCHAR(20)     NOT NULL,
    source_invoice_uid   VARCHAR(26),
    document_no          VARCHAR(30),
    original_amount      NUMERIC(19,4)   NOT NULL,
    outstanding_amount   NUMERIC(19,4)   NOT NULL,
    currency             VARCHAR(3)      NOT NULL,
    invoice_date         DATE            NOT NULL,
    due_date             DATE            NOT NULL,
    status               VARCHAR(20)     NOT NULL DEFAULT 'OPEN',
    version              BIGINT          NOT NULL DEFAULT 0,
    created_at           TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by           BIGINT,
    updated_at           TIMESTAMPTZ,
    updated_by           BIGINT,

    CONSTRAINT uq_ar_invoice_uid        UNIQUE (uid),
    CONSTRAINT fk_ar_invoice_company    FOREIGN KEY (company_id)  REFERENCES companies (id),
    CONSTRAINT fk_ar_invoice_branch     FOREIGN KEY (branch_id)   REFERENCES branches (id),
    CONSTRAINT fk_ar_invoice_customer   FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT chk_ar_invoice_source    CHECK (source IN ('SALE','OPENING_BALANCE')),
    CONSTRAINT chk_ar_invoice_status    CHECK (status IN ('OPEN','PARTIAL','PAID','WRITTEN_OFF')),
    CONSTRAINT chk_ar_invoice_amounts   CHECK (
        original_amount > 0
        AND outstanding_amount >= 0
        AND outstanding_amount <= original_amount),
    CONSTRAINT chk_ar_invoice_dates     CHECK (due_date >= invoice_date)
);

-- Partial unique: one open item per source invoice per company (FR-AR-04, BR-AR-08)
CREATE UNIQUE INDEX uq_ar_invoice_source_sale
    ON ar_invoices (company_id, source_invoice_uid)
    WHERE source = 'SALE';

-- ============================================================================
-- (2) ar_receipts — money received (RCT-####)
-- ============================================================================
CREATE TABLE ar_receipts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                 VARCHAR(26)     NOT NULL,
    company_id          BIGINT          NOT NULL,
    branch_id           BIGINT,
    customer_id         BIGINT          NOT NULL,
    receipt_number      VARCHAR(30)     NOT NULL,
    receipt_date        DATE            NOT NULL,
    amount              NUMERIC(19,4)   NOT NULL,
    unallocated_amount  NUMERIC(19,4)   NOT NULL,
    currency            VARCHAR(3)      NOT NULL,
    tender_type         VARCHAR(20)     NOT NULL,
    bank_reference      VARCHAR(80),
    gl_entry_uid        VARCHAR(26),
    status              VARCHAR(20)     NOT NULL DEFAULT 'UNALLOCATED',
    version             BIGINT          NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ,
    updated_by          BIGINT,

    CONSTRAINT uq_ar_receipt_uid            UNIQUE (uid),
    CONSTRAINT uq_ar_receipt_company_number UNIQUE (company_id, receipt_number),
    CONSTRAINT fk_ar_receipt_company        FOREIGN KEY (company_id)  REFERENCES companies (id),
    CONSTRAINT fk_ar_receipt_branch         FOREIGN KEY (branch_id)   REFERENCES branches (id),
    CONSTRAINT fk_ar_receipt_customer       FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT chk_ar_receipt_amount        CHECK (amount > 0),
    CONSTRAINT chk_ar_receipt_unallocated   CHECK (
        unallocated_amount >= 0 AND unallocated_amount <= amount),
    CONSTRAINT chk_ar_receipt_tender        CHECK (
        tender_type IN ('CASH','BANK_TRANSFER','MOBILE_MONEY')),
    CONSTRAINT chk_ar_receipt_status        CHECK (
        status IN ('UNALLOCATED','PARTIAL','ALLOCATED'))
);

-- ============================================================================
-- (3) ar_receipt_allocations — junction: receipt ↔ open item (singular per convention)
-- ============================================================================
CREATE TABLE ar_receipt_allocations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id       BIGINT          NOT NULL,
    receipt_id       BIGINT          NOT NULL,
    ar_invoice_id    BIGINT          NOT NULL,
    allocated_amount NUMERIC(19,4)   NOT NULL,
    allocated_at     TIMESTAMPTZ     NOT NULL DEFAULT now(),
    allocated_by     BIGINT,
    created_at       TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by       BIGINT,

    CONSTRAINT uq_ar_receipt_allocation_pair UNIQUE (receipt_id, ar_invoice_id),
    CONSTRAINT fk_ar_receipt_allocation_company FOREIGN KEY (company_id)    REFERENCES companies (id),
    CONSTRAINT fk_ar_receipt_allocation_receipt FOREIGN KEY (receipt_id)    REFERENCES ar_receipts (id),
    CONSTRAINT fk_ar_receipt_allocation_invoice FOREIGN KEY (ar_invoice_id) REFERENCES ar_invoices (id),
    CONSTRAINT chk_ar_receipt_allocation_amount CHECK (allocated_amount > 0)
);

-- ============================================================================
-- (4) ar_credit_notes — reduce a receivable (CRN-####)
-- ============================================================================
CREATE TABLE ar_credit_notes (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                   VARCHAR(26)     NOT NULL,
    company_id            BIGINT          NOT NULL,
    branch_id             BIGINT,
    customer_id           BIGINT          NOT NULL,
    credit_note_number    VARCHAR(30)     NOT NULL,
    ar_invoice_id         BIGINT,
    note_date             DATE            NOT NULL,
    amount                NUMERIC(19,4)   NOT NULL,
    net_amount            NUMERIC(19,4)   NOT NULL,
    vat_amount            NUMERIC(19,4)   NOT NULL DEFAULT 0,
    currency              VARCHAR(3)      NOT NULL,
    reason                VARCHAR(255)    NOT NULL,
    origin                VARCHAR(20)     NOT NULL DEFAULT 'STANDALONE',
    gl_entry_uid          VARCHAR(26),
    -- D-6: unapplied tracking + base capture + FX rate (ADR-0040 D-6, receipt parity)
    unapplied_amount      NUMERIC(19,4)   NOT NULL DEFAULT 0,
    base_amount           NUMERIC(19,4),
    base_unapplied_amount NUMERIC(19,4),
    fx_rate               NUMERIC(19,8)   NOT NULL DEFAULT 1,
    rate_at               TIMESTAMPTZ,
    status                VARCHAR(20)     NOT NULL DEFAULT 'UNAPPLIED',
    version               BIGINT          NOT NULL DEFAULT 0,
    created_at            TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by            BIGINT,
    updated_at            TIMESTAMPTZ,
    updated_by            BIGINT,

    CONSTRAINT uq_ar_credit_note_uid            UNIQUE (uid),
    CONSTRAINT uq_ar_credit_note_company_number UNIQUE (company_id, credit_note_number),
    CONSTRAINT fk_ar_credit_note_company        FOREIGN KEY (company_id)    REFERENCES companies (id),
    CONSTRAINT fk_ar_credit_note_branch         FOREIGN KEY (branch_id)     REFERENCES branches (id),
    CONSTRAINT fk_ar_credit_note_customer       FOREIGN KEY (customer_id)   REFERENCES customers (id),
    CONSTRAINT fk_ar_credit_note_invoice        FOREIGN KEY (ar_invoice_id) REFERENCES ar_invoices (id),
    CONSTRAINT chk_ar_credit_note_amount        CHECK (
        amount > 0 AND net_amount >= 0 AND vat_amount >= 0),
    CONSTRAINT chk_ar_credit_note_origin        CHECK (
        origin IN ('STANDALONE','SALE_VOID')),
    CONSTRAINT chk_ar_credit_note_unapplied     CHECK (
        unapplied_amount >= 0 AND unapplied_amount <= amount),
    CONSTRAINT chk_ar_credit_note_status        CHECK (
        status IN ('UNAPPLIED','PARTIAL','APPLIED'))
);

-- ============================================================================
-- (4b) ar_credit_note_allocations — junction: CN ↔ open item (ADR-0040 D-6)
--      No uid (junction convention, mirrors ar_receipt_allocations).
--      Append-only; reapply = delete + re-insert; posting nothing to GL (only FX plug).
-- ============================================================================
CREATE TABLE ar_credit_note_allocations (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id            BIGINT          NOT NULL,
    credit_note_id        BIGINT          NOT NULL,
    ar_invoice_id         BIGINT          NOT NULL,
    allocated_amount      NUMERIC(19,4)   NOT NULL,
    base_allocated_amount NUMERIC(19,4),
    settlement_rate       NUMERIC(19,8),
    allocated_at          TIMESTAMPTZ     NOT NULL DEFAULT now(),
    allocated_by          BIGINT,
    created_at            TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by            BIGINT,

    CONSTRAINT uq_ar_credit_note_allocation_pair    UNIQUE (credit_note_id, ar_invoice_id),
    CONSTRAINT fk_ar_cn_allocation_company          FOREIGN KEY (company_id)    REFERENCES companies (id),
    CONSTRAINT fk_ar_cn_allocation_credit_note      FOREIGN KEY (credit_note_id) REFERENCES ar_credit_notes (id),
    CONSTRAINT fk_ar_cn_allocation_invoice          FOREIGN KEY (ar_invoice_id)  REFERENCES ar_invoices (id),
    CONSTRAINT chk_ar_cn_allocation_amount          CHECK (allocated_amount > 0)
);

