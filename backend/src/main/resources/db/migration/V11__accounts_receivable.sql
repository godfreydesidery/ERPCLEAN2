-- ============================================================================
-- (7) CoA seed — add 5500 Bad Debt Expense + 3100 Opening Balance Equity
-- per existing company (CROSS JOIN; deterministic seed-uid; V10 pattern).
-- ============================================================================
INSERT INTO chart_of_accounts (
    uid, company_id, account_code, name, account_type, normal_balance,
    is_active, status, version, created_at
)
SELECT
    'ARSD' || lpad(c.id::text, 6, '0') || a.code AS uid,
    c.id,
    a.code,
    a.name,
    a.account_type,
    a.normal_balance,
    true,
    'ACTIVE',
    0,
    now()
FROM companies c
CROSS JOIN (VALUES
    ('5500', 'Bad Debt Expense',        'EXPENSE', 'DEBIT'),
    ('3100', 'Opening Balance Equity',  'EQUITY',  'CREDIT')
) AS a(code, name, account_type, normal_balance)
ON CONFLICT (company_id, account_code) DO NOTHING;

-- ============================================================================
-- (8) gl_configs CHECK constraint — widen to admit BAD_DEBT_EXPENSE and
-- OPENING_BALANCE_EQUITY (additive ALTER; never editing V10 DDL).
-- ============================================================================
ALTER TABLE gl_configs
    DROP CONSTRAINT IF EXISTS chk_gl_config_key;

ALTER TABLE gl_configs
    ADD CONSTRAINT chk_gl_config_key CHECK (
        config_key IN (
            'SALES_REVENUE','VAT_PAYABLE','ACCOUNTS_RECEIVABLE','CASH',
            'INVENTORY','COGS','ACCOUNTS_PAYABLE',
            'BAD_DEBT_EXPENSE','OPENING_BALANCE_EQUITY'
        ));

-- Seed BAD_DEBT_EXPENSE → 5500 and OPENING_BALANCE_EQUITY → 3100 per company.
INSERT INTO gl_configs (uid, company_id, config_key, account_id, version, created_at)
SELECT
    -- <=26-char uid (ISSUES-REGISTER #12): raw config_key (e.g. OPENING_BALANCE_EQUITY) overflowed
    -- uid VARCHAR(26) when seeding a DB that already has companies. md5(key) keeps it bounded.
    'ARC' || lpad(coa.company_id::text, 6, '0') || substr(md5(m.config_key), 1, 12) AS uid,
    coa.company_id,
    m.config_key,
    coa.id,
    0,
    now()
FROM (VALUES
    ('BAD_DEBT_EXPENSE',       '5500'),
    ('OPENING_BALANCE_EQUITY', '3100')
) AS m(config_key, account_code)
JOIN chart_of_accounts coa ON coa.account_code = m.account_code
ON CONFLICT (company_id, config_key) DO NOTHING;

-- ============================================================================
-- (9) journal source-type CHECK widen — add AR_RECEIPT, AR_WRITEOFF, AR_CREDIT_NOTE
-- (additive ALTER on journal_batches + journal_entries; V10 DDL untouched).
-- ============================================================================
ALTER TABLE journal_batches
    DROP CONSTRAINT IF EXISTS chk_journal_batch_source_type;

ALTER TABLE journal_batches
    ADD CONSTRAINT chk_journal_batch_source_type CHECK (
        source_type IN (
            'MANUAL','SALES','SALES_REVERSAL','OPENING_BALANCE',
            'AR_RECEIPT','AR_WRITEOFF','AR_CREDIT_NOTE'
        ));

ALTER TABLE journal_entries
    DROP CONSTRAINT IF EXISTS chk_journal_entry_source_type;

ALTER TABLE journal_entries
    ADD CONSTRAINT chk_journal_entry_source_type CHECK (
        source_type IN (
            'MANUAL','SALES','SALES_REVERSAL','OPENING_BALANCE',
            'AR_RECEIPT','AR_WRITEOFF','AR_CREDIT_NOTE'
        ));
