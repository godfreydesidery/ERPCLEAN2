-- ---------------------------------------------------------------------------
-- Slice 6: audit_logs — append-only IAM (and later, global) action trail
-- (DATA-MODEL §1.11, ADR-0004 D-1). Internal table, no uid column (ADR-0001 D-G).
-- No version/updated_* columns — append-only (D-5). FK to app_users is SQL-only;
-- platform.audit depends on no module entity (D-1). NO trigger (owner ruling D-5).
-- ---------------------------------------------------------------------------
CREATE TABLE audit_logs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT,
    action        VARCHAR(80)  NOT NULL,
    target_type   VARCHAR(60)  NOT NULL,
    target_id     BIGINT,
    target_uid    VARCHAR(26),
    company_id    BIGINT,
    branch_id     BIGINT,
    detail        JSONB,
    at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ip            VARCHAR(45),
    CONSTRAINT fk_audit_log_actor FOREIGN KEY (actor_user_id) REFERENCES app_users (id)
);

-- Query patterns: history of a specific target entity; actions by a specific actor; action/time range.
CREATE INDEX ix_audit_log_target    ON audit_logs (target_type, target_id, at);
CREATE INDEX ix_audit_log_actor     ON audit_logs (actor_user_id, at);
CREATE INDEX ix_audit_log_action_at ON audit_logs (action, at);
