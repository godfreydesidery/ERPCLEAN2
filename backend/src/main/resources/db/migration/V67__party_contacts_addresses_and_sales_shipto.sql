    updated_by       BIGINT,
    CONSTRAINT uq_customer_address_uid      UNIQUE (uid),
    CONSTRAINT fk_customer_address_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT fk_customer_address_company  FOREIGN KEY (company_id)  REFERENCES companies (id),
    CONSTRAINT chk_customer_address_role    CHECK (address_role IN ('BILL_TO','SHIP_TO','GENERAL'))
