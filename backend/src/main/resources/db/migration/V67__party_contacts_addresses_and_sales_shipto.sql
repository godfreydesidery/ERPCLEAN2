-- ---------------------------------------------------------------------------
-- customer_contacts
-- ---------------------------------------------------------------------------
CREATE TABLE customer_contacts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid              VARCHAR(26)      NOT NULL,
    company_id       BIGINT           NOT NULL,
    customer_id      BIGINT           NOT NULL,
    contact_person   VARCHAR(160),
    phone            VARCHAR(40),
    email            VARCHAR(160),
    is_primary       BOOLEAN          NOT NULL DEFAULT false,
    status           VARCHAR(32)      NOT NULL DEFAULT 'ACTIVE',
    version          BIGINT           NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ      NOT NULL DEFAULT now(),
    created_by       BIGINT,
    updated_at       TIMESTAMPTZ,
    updated_by       BIGINT,
    CONSTRAINT uq_customer_contact_uid      UNIQUE (uid),
    CONSTRAINT fk_customer_contact_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT fk_customer_contact_company  FOREIGN KEY (company_id)  REFERENCES companies (id)
);

CREATE UNIQUE INDEX uq_customer_contacts_primary
    ON customer_contacts (customer_id) WHERE is_primary;
CREATE INDEX ix_customer_contacts_customer
    ON customer_contacts (customer_id);

