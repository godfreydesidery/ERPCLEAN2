-- ============================================================================
-- (8) gl_configs CHECK constraint — widen to admit VAT_INPUT, VAT_DUE,
--     WHT_PAYABLE, WHT_RECEIVABLE (additive ALTER; V10/V11/V12/V13 DDL untouched).
-- ============================================================================
ALTER TABLE gl_configs
    DROP CONSTRAINT IF EXISTS chk_gl_config_key;

ALTER TABLE gl_configs
    ADD CONSTRAINT chk_gl_config_key CHECK (
        config_key IN (
            'SALES_REVENUE','VAT_PAYABLE','ACCOUNTS_RECEIVABLE','CASH',
            'INVENTORY','COGS','ACCOUNTS_PAYABLE',
            'BAD_DEBT_EXPENSE','OPENING_BALANCE_EQUITY',
            'PURCHASES',
            'VAT_INPUT','VAT_DUE','WHT_PAYABLE','WHT_RECEIVABLE'
        ));

-- Seed the 4 new gl_configs keys per company (joining the just-seeded CoA).
-- CRITICAL #12-safe seed-uid: 'VTC' || lpad(company_id,6,'0') || substr(md5(key),1,12) = 21 chars.
-- NEVER use || config_key (WHT_RECEIVABLE=14 chars would overflow with longer prefixes).
INSERT INTO gl_configs (uid, company_id, config_key, account_id, version, created_at)
SELECT
    'VTC' || lpad(coa.company_id::text, 6, '0') || substr(md5(m.config_key), 1, 12) AS uid,
    coa.company_id,
    m.config_key,
    coa.id,
    0,
    now()
FROM (VALUES
    ('VAT_INPUT',        '1400'),
    ('VAT_DUE',          '2300'),
    ('WHT_PAYABLE',      '2400'),
    ('WHT_RECEIVABLE',   '1500')
) AS m(config_key, account_code)
JOIN chart_of_accounts coa ON coa.account_code = m.account_code
ON CONFLICT (company_id, config_key) DO NOTHING;

