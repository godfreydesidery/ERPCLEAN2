-- ============================================================================
-- (7) CoA seed — add 4 new accounts per existing company
-- Seeds: 1400 VAT Input (ASSET/DEBIT), 1500 WHT Receivable (ASSET/DEBIT),
--        2300 VAT Due (LIABILITY/CREDIT), 2400 WHT Payable (LIABILITY/CREDIT).
-- Deterministic seed-uid uses account_code suffix (≤14 chars).
-- ============================================================================
INSERT INTO chart_of_accounts (
    uid, company_id, account_code, name, account_type, normal_balance,
    is_active, status, version, created_at
)
SELECT
    'VATC' || lpad(c.id::text, 6, '0') || '1400' AS uid,
    c.id,
    '1400',
    'VAT Input (Recoverable)',
    'ASSET',
    'DEBIT',
    true,
    'ACTIVE',
    0,
    now()
FROM companies c
ON CONFLICT (company_id, account_code) DO NOTHING;

