-- ============================================================================
INSERT INTO permissions (code, module, description) VALUES
    ('COSTING.VIEW',   'costing',
     'View dimensions, dimension values (cost centres / departments), and the dimension-sliced trial balance'),
    ('COSTING.MANAGE', 'costing',
     'Maintain dimension values (create/edit/deactivate) and set a dimension mandatory/optional'),
    ('COSTING.TAG',    'costing',
     'Pick dimension values on a journal / invoice / bill / adjustment when posting')
ON CONFLICT (code) DO NOTHING;

INSERT INTO role_permission (role_id, permission_id)
SELECT r.id, p.id
FROM   roles r
CROSS JOIN permissions p
WHERE  r.code   = 'ORG_ADMIN'
  AND  p.code IN ('COSTING.VIEW', 'COSTING.MANAGE', 'COSTING.TAG')
ON CONFLICT DO NOTHING;

-- ============================================================================
-- (5) Dimension seed per existing company — built-in COST_CENTRE + DEPARTMENT (ADR-0025 D-9)
-- CRITICAL #12-safe seed-uid: 'DIM' || lpad(company_id,6,'0') || substr(md5(slot),1,12)
--   = 3+6+12 = 21 chars (<=26). NEVER || slot directly (overflow risk, ISSUES-REGISTER #12).
-- is_built_in=true — cannot be deleted (FR-CC-01).
-- is_mandatory=false — opt-in governance, off by default (BR-CC-03, NFR-CC-01).
-- ON CONFLICT (company_id, slot) DO NOTHING — idempotent on keep-data re-deploy.
-- ============================================================================
INSERT INTO dimensions (uid, company_id, slot, code, name, is_built_in, is_mandatory, status, version, created_at)
SELECT
    'DIM' || lpad(c.id::text, 6, '0') || substr(md5(s.slot), 1, 12) AS uid,
    c.id,
    s.slot,
    s.code,
    s.name,
    true,
    false,
    'ACTIVE',
    0,
    now()
FROM companies c
CROSS JOIN (VALUES
    ('COST_CENTRE', 'COST_CENTRE', 'Cost Centre'),
    ('DEPARTMENT',  'DEPARTMENT',  'Department')
) AS s(slot, code, name)
ON CONFLICT (company_id, slot) DO NOTHING;
