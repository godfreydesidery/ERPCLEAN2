-- ============================================================================
-- (6) CoA back-seed — 2160 Landed Cost Clearing per existing company
-- uid: 'PC' || lpad(company_id, 6, '0') || '2160' = 2+6+4 = 12 chars (<=26)
-- ON CONFLICT (company_id, account_code) DO NOTHING — idempotent.
-- ============================================================================
INSERT INTO chart_of_accounts (
    uid, company_id, account_code, name, account_type, normal_balance,
    is_active, status, version, created_at
)
SELECT
    'PC' || lpad(c.id::text, 6, '0') || '2160' AS uid,
    c.id,
    '2160',
    'Landed Cost Clearing',
    'LIABILITY',
    'CREDIT',
    true,
    'ACTIVE',
    0,
    now()
FROM companies c
ON CONFLICT (company_id, account_code) DO NOTHING;

-- ============================================================================
-- (7) chk_gl_config_key widen — FULL union of ALL prior keys + LANDED_COST_CLEARING
-- Prior union at V46: V17 keys + FA keys. Our V32-V34 come BEFORE V37+, so we build
-- the union of V17 + FA (from V46) + LANDED_COST_CLEARING here.
-- Since V34 < V46 in number, but V46 is already on this branch (in-flight):
-- we must include the FA keys so our constraint doesn't conflict if V46 runs after us.
-- IMPORTANT: V46 will re-DROP and re-ADD with its own union which includes FA keys.
-- If V34 runs BEFORE V46, we set keys = V17 + LANDED_COST_CLEARING.
-- If V46 runs AFTER V34, V46 will widen again to include FA keys.
-- Since V32-V36 < V46 numerically, V32-V36 run first.
-- So here we include only V17 keys + LANDED_COST_CLEARING.
-- V46 will then add FA keys on top.
-- ============================================================================
ALTER TABLE gl_configs
    DROP CONSTRAINT IF EXISTS chk_gl_config_key;

ALTER TABLE gl_configs
    ADD CONSTRAINT chk_gl_config_key CHECK (
        config_key IN (
            'SALES_REVENUE','VAT_PAYABLE','ACCOUNTS_RECEIVABLE','CASH',
            'INVENTORY','COGS','ACCOUNTS_PAYABLE',
            'BAD_DEBT_EXPENSE','OPENING_BALANCE_EQUITY',
            'PURCHASES',
            'VAT_INPUT','VAT_DUE','WHT_PAYABLE','WHT_RECEIVABLE',
            'RETAINED_EARNINGS',
            'GRNI','STOCK_ADJUSTMENT',
            -- procurement-depth (ADR-0027) ---
            'LANDED_COST_CLEARING'
        ));

-- ============================================================================
-- (8) gl_configs back-seed: LANDED_COST_CLEARING → 2160 per existing company
-- uid: 'PG' || lpad(company_id, 6, '0') || substr(md5('LANDED_COST_CLEARING'), 1, 12)
--    = 2+6+12 = 20 chars (<=26). #12-safe. ON CONFLICT (company_id, config_key) DO NOTHING.
-- ============================================================================
INSERT INTO gl_configs (uid, company_id, config_key, account_id, version, created_at)
SELECT
    'PG' || lpad(coa.company_id::text, 6, '0') || substr(md5('LANDED_COST_CLEARING'), 1, 12) AS uid,
    coa.company_id,
    'LANDED_COST_CLEARING',
    coa.id,
    0,
    now()
FROM chart_of_accounts coa
WHERE coa.account_code = '2160'
ON CONFLICT (company_id, config_key) DO NOTHING;

