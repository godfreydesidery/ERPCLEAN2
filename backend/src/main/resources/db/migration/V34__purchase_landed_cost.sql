-- V34 — Procurement depth: landed_costs + landed_cost_receipts + landed_cost_charges
--        + landed_cost_allocations; CoA back-seed 2160 Landed Cost Clearing;
--        chk_gl_config_key widen (FULL union incl. LANDED_COST_CLEARING);
--        gl_configs key back-seed; ALTER supplier_bill_lines ADD landed_cost_uid;
--        journal source-type CHECK widen (add LANDED_COST);
--        permission seed + ORG_ADMIN grant.
-- Additive only. V1–V33 are FROZEN/in-flight.
-- ADR-0027 D-5 / D-7 / D-8 / D-9 / D-10 / D-12.

-- ============================================================================
-- (1) landed_costs — LC header
-- ============================================================================
CREATE TABLE landed_costs (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                     VARCHAR(26)      NOT NULL,
    company_id              BIGINT           NOT NULL,
    branch_id               BIGINT           NOT NULL,
    landed_cost_number      VARCHAR(30)      NOT NULL,            -- LC-####; assigned at create
    status                  VARCHAR(20)      NOT NULL DEFAULT 'DRAFT',
    basis                   VARCHAR(20)      NOT NULL DEFAULT 'BY_VALUE',
    total_charge_amount     NUMERIC(19,4)    NOT NULL DEFAULT 0,
    currency                VARCHAR(3)       NOT NULL DEFAULT 'TZS',
    gl_entry_uid            VARCHAR(26),                          -- capitalisation journal uid (diagnostic)
    notes                   VARCHAR(500),
    confirmed_at            TIMESTAMPTZ,
    confirmed_by            BIGINT,
    version                 BIGINT           NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ      NOT NULL DEFAULT now(),
    created_by              BIGINT,
    updated_at              TIMESTAMPTZ,
    updated_by              BIGINT,

    CONSTRAINT uq_landed_cost_uid            UNIQUE (uid),
    CONSTRAINT uq_landed_cost_company_number UNIQUE (company_id, landed_cost_number),
    CONSTRAINT fk_landed_cost_company        FOREIGN KEY (company_id)   REFERENCES companies (id),
    CONSTRAINT fk_landed_cost_branch         FOREIGN KEY (branch_id)    REFERENCES branches (id),
    CONSTRAINT fk_landed_cost_confirmed_by   FOREIGN KEY (confirmed_by) REFERENCES app_users (id),
    CONSTRAINT chk_landed_cost_status        CHECK (status IN ('DRAFT','CONFIRMED')),
    CONSTRAINT chk_landed_cost_basis         CHECK (basis IN ('BY_VALUE','BY_QUANTITY')),
    CONSTRAINT chk_landed_cost_total         CHECK (total_charge_amount >= 0)
);

-- ============================================================================
-- (2) landed_cost_receipts — junction: the GRs this LC covers
-- ============================================================================
CREATE TABLE landed_cost_receipt (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                     VARCHAR(26)      NOT NULL,
    landed_cost_id          BIGINT           NOT NULL,
    goods_receipt_id        BIGINT           NOT NULL,
    goods_receipt_uid       VARCHAR(26)      NOT NULL,
    company_id              BIGINT           NOT NULL,
    branch_id               BIGINT           NOT NULL,
    version                 BIGINT           NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ      NOT NULL DEFAULT now(),
    created_by              BIGINT,

    CONSTRAINT uq_landed_cost_receipt_uid UNIQUE (uid),
    CONSTRAINT uq_landed_cost_receipt     UNIQUE (landed_cost_id, goods_receipt_id),
    CONSTRAINT fk_landed_cost_receipt_lc  FOREIGN KEY (landed_cost_id)   REFERENCES landed_costs (id),
    CONSTRAINT fk_landed_cost_receipt_gr  FOREIGN KEY (goods_receipt_id) REFERENCES goods_receipts (id),
    CONSTRAINT fk_landed_cost_receipt_co  FOREIGN KEY (company_id)       REFERENCES companies (id),
    CONSTRAINT fk_landed_cost_receipt_br  FOREIGN KEY (branch_id)        REFERENCES branches (id)
);

-- ============================================================================
-- (3) landed_cost_charges — charge lines (freight/duty/etc.)
-- ============================================================================
CREATE TABLE landed_cost_charges (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                     VARCHAR(26)      NOT NULL,
    landed_cost_id          BIGINT           NOT NULL,
    company_id              BIGINT           NOT NULL,
    branch_id               BIGINT           NOT NULL,
    line_no                 SMALLINT         NOT NULL,
    charge_type             VARCHAR(20)      NOT NULL,
    amount                  NUMERIC(19,4)    NOT NULL,
    is_billed               BOOLEAN          NOT NULL DEFAULT false,
    supplier_bill_uid       VARCHAR(26),                          -- the freight bill if is_billed
    currency                VARCHAR(3)       NOT NULL DEFAULT 'TZS',
    version                 BIGINT           NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ      NOT NULL DEFAULT now(),
    created_by              BIGINT,
    updated_at              TIMESTAMPTZ,
    updated_by              BIGINT,

    CONSTRAINT uq_landed_cost_charge_uid UNIQUE (uid),
    CONSTRAINT uq_landed_cost_charge_no  UNIQUE (landed_cost_id, line_no),
    CONSTRAINT fk_landed_cost_charge_lc  FOREIGN KEY (landed_cost_id) REFERENCES landed_costs (id),
    CONSTRAINT fk_landed_cost_charge_co  FOREIGN KEY (company_id)     REFERENCES companies (id),
    CONSTRAINT fk_landed_cost_charge_br  FOREIGN KEY (branch_id)      REFERENCES branches (id),
    CONSTRAINT chk_landed_cost_charge_type
        CHECK (charge_type IN ('FREIGHT','DUTY','CLEARING','INSURANCE','OTHER')),
    CONSTRAINT chk_landed_cost_charge_amount  CHECK (amount > 0),
    CONSTRAINT chk_landed_cost_charge_billed
        CHECK ((is_billed = false AND supplier_bill_uid IS NULL)
            OR (is_billed = true  AND supplier_bill_uid IS NOT NULL))
);

-- ============================================================================
-- (4) landed_cost_allocations — per-receipt-line allocation amounts (the maths audit)
-- ============================================================================
CREATE TABLE landed_cost_allocations (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                     VARCHAR(26)      NOT NULL,
    landed_cost_id          BIGINT           NOT NULL,
    goods_receipt_line_id   BIGINT           NOT NULL,
    goods_receipt_line_uid  VARCHAR(26)      NOT NULL,
    product_id              BIGINT           NOT NULL,
    company_id              BIGINT           NOT NULL,
    branch_id               BIGINT           NOT NULL,
    allocated_amount        NUMERIC(19,4)    NOT NULL,
    currency                VARCHAR(3)       NOT NULL DEFAULT 'TZS',
    version                 BIGINT           NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ      NOT NULL DEFAULT now(),
    created_by              BIGINT,

    CONSTRAINT uq_landed_cost_allocation_uid UNIQUE (uid),
    CONSTRAINT uq_landed_cost_allocation     UNIQUE (landed_cost_id, goods_receipt_line_id),
    CONSTRAINT fk_landed_cost_alloc_lc       FOREIGN KEY (landed_cost_id)         REFERENCES landed_costs (id),
    CONSTRAINT fk_landed_cost_alloc_grl      FOREIGN KEY (goods_receipt_line_id)  REFERENCES goods_receipt_lines (id),
    CONSTRAINT fk_landed_cost_alloc_product  FOREIGN KEY (product_id)             REFERENCES products (id),
    CONSTRAINT fk_landed_cost_alloc_co       FOREIGN KEY (company_id)             REFERENCES companies (id),
    CONSTRAINT fk_landed_cost_alloc_br       FOREIGN KEY (branch_id)              REFERENCES branches (id),
    CONSTRAINT chk_landed_cost_alloc_amount  CHECK (allocated_amount >= 0)
);

-- ============================================================================
