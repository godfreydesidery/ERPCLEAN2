-- customer_branch
CREATE TABLE customer_branch (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT          NOT NULL,
    branch_id   BIGINT          NOT NULL,
    assigned_at TIMESTAMPTZ     NOT NULL DEFAULT now(),
    assigned_by BIGINT          NOT NULL,
    CONSTRAINT uq_customer_branch_pair  UNIQUE (customer_id, branch_id),
    CONSTRAINT fk_customer_branch_cust  FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT fk_customer_branch_br    FOREIGN KEY (branch_id)   REFERENCES branches (id),
    CONSTRAINT fk_customer_branch_by    FOREIGN KEY (assigned_by)  REFERENCES app_users (id)
