-- V2 — Parties module: customers, suppliers, agents, other_parties
-- Additive only. V1 (IAM) is FROZEN — this file does not edit it.
-- Order per ADR-0006 D-13:
--   (1) master tables → (2) party_code_sequence → (3) link tables
--   → (4) indexes (partial / expression) → (5) permission seed + ORG_ADMIN grant.

-- ---------------------------------------------------------------------------
-- (1a) customers
-- ---------------------------------------------------------------------------
CREATE TABLE customers (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                     VARCHAR(26)     NOT NULL,
    company_id              BIGINT          NOT NULL,
    code                    VARCHAR(20)     NOT NULL,
    party_type              VARCHAR(20)     NOT NULL,
    display_name            VARCHAR(200)    NOT NULL,
    legal_name              VARCHAR(200),
    tin                     VARCHAR(20),
    vat_registered          BOOLEAN         NOT NULL DEFAULT false,
    vrn                     VARCHAR(20),
    business_reg_no         VARCHAR(40),
    mobile_money_no         VARCHAR(30),
    phone                   VARCHAR(40),
    email                   VARCHAR(160),
    physical_address        VARCHAR(255),
    postal_address          VARCHAR(255),
    region                  VARCHAR(80),
    district                VARCHAR(80),
    customer_kind           VARCHAR(20)     NOT NULL,
    credit_limit_amount     NUMERIC(19,4),
    credit_limit_currency   VARCHAR(3),
    payment_terms_days      INTEGER,
    status                  VARCHAR(32)     NOT NULL DEFAULT 'ACTIVE',
    version                 BIGINT          NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by              BIGINT,
    updated_at              TIMESTAMPTZ,
    updated_by              BIGINT,
    CONSTRAINT uq_customer_uid          UNIQUE (uid),
    CONSTRAINT uq_customer_company_code UNIQUE (company_id, code),
    CONSTRAINT fk_customer_company      FOREIGN KEY (company_id) REFERENCES companies (id),
    CONSTRAINT chk_customer_party_type  CHECK (party_type IN ('INDIVIDUAL','BUSINESS')),
    CONSTRAINT chk_customer_kind        CHECK (customer_kind IN ('CASH_WALK_IN','CREDIT_ACCOUNT')),
    CONSTRAINT chk_customer_vrn_vat     CHECK (vrn IS NULL OR vat_registered = true),
    CONSTRAINT chk_customer_credit_pair CHECK (
        (credit_limit_amount IS NULL AND credit_limit_currency IS NULL) OR
        (credit_limit_amount IS NOT NULL AND credit_limit_currency IS NOT NULL)
    )
);

