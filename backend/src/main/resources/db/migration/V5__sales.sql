-- V5 — Sales module: products.vat_status ALTER + tax_rates + 3 sales tables + perms.
-- Additive only. V1 (IAM) / V2 (Parties) / V3 (Products) / V4 (Units) are FROZEN.
-- Order per ADR-0008 D-14.

-- (1) Additive product VAT-status column (the one cross-module touch; safe default).
ALTER TABLE products
    ADD COLUMN vat_status VARCHAR(20) NOT NULL DEFAULT 'STANDARD';
ALTER TABLE products
    ADD CONSTRAINT chk_product_vat_status
    CHECK (vat_status IN ('STANDARD','ZERO_RATED','EXEMPT'));

-- (2) tax_rates master (D-5b)
CREATE TABLE tax_rates (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid         VARCHAR(26)     NOT NULL,
    company_id  BIGINT          NOT NULL,
    vat_status  VARCHAR(20)     NOT NULL,
    rate        NUMERIC(9,4)    NOT NULL,
    status      VARCHAR(32)     NOT NULL DEFAULT 'ACTIVE',
    version     BIGINT          NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_at  TIMESTAMPTZ,
    updated_by  BIGINT,
    CONSTRAINT uq_tax_rate_uid             UNIQUE (uid),
    CONSTRAINT uq_tax_rate_company_status  UNIQUE (company_id, vat_status),
    CONSTRAINT fk_tax_rate_company         FOREIGN KEY (company_id) REFERENCES companies (id),
    CONSTRAINT chk_tax_rate_vat_status     CHECK (vat_status IN ('STANDARD','ZERO_RATED','EXEMPT')),
    CONSTRAINT chk_tax_rate_value          CHECK (rate >= 0 AND rate < 1)
);

-- (3) Seed tax_rates for every existing company (CROSS JOIN, deterministic seed-uid; V4 §2 pattern).
INSERT INTO tax_rates (uid, company_id, vat_status, rate, status, version, created_at)
SELECT
    'SEED' || lpad(c.id::text, 10, '0') || rpad(t.vat_status, 12, '_') AS uid,
    c.id, t.vat_status, t.rate, 'ACTIVE', 0, now()
FROM companies c
CROSS JOIN (VALUES
    ('STANDARD',   0.1800),
    ('ZERO_RATED', 0.0000),
    ('EXEMPT',     0.0000)
) AS t(vat_status, rate);

-- (4) sales_invoices (header)
CREATE TABLE sales_invoices (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                 VARCHAR(26)     NOT NULL,
    company_id          BIGINT          NOT NULL,
    branch_id           BIGINT          NOT NULL,
    document_type       VARCHAR(20)     NOT NULL DEFAULT 'INVOICE',
    invoice_number      VARCHAR(30),
    status              VARCHAR(20)     NOT NULL DEFAULT 'DRAFT',
    customer_id         BIGINT          NOT NULL,
    agent_id            BIGINT          NOT NULL,
    currency            VARCHAR(3)      NOT NULL,
    doc_discount_amount  NUMERIC(19,4),
    doc_discount_percent NUMERIC(9,4),
    net_total_amount    NUMERIC(19,4)   NOT NULL DEFAULT 0,
    vat_total_amount    NUMERIC(19,4)   NOT NULL DEFAULT 0,
    gross_total_amount  NUMERIC(19,4)   NOT NULL DEFAULT 0,
    tax_summary         JSONB,
    finalised_at        TIMESTAMPTZ,
    finalised_by        BIGINT,
    voided_at           TIMESTAMPTZ,
    voided_by           BIGINT,
    void_reason         VARCHAR(255),
    notes               VARCHAR(500),
    version             BIGINT          NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ,
    updated_by          BIGINT,
    CONSTRAINT uq_sales_invoice_uid             UNIQUE (uid),
    CONSTRAINT uq_sales_invoice_company_number  UNIQUE (company_id, invoice_number),
    CONSTRAINT fk_sales_invoice_company         FOREIGN KEY (company_id)  REFERENCES companies (id),
    CONSTRAINT fk_sales_invoice_branch          FOREIGN KEY (branch_id)   REFERENCES branches (id),
    CONSTRAINT fk_sales_invoice_customer        FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT fk_sales_invoice_agent           FOREIGN KEY (agent_id)    REFERENCES agents (id),
    CONSTRAINT fk_sales_invoice_finalised_by    FOREIGN KEY (finalised_by) REFERENCES app_users (id),
    CONSTRAINT fk_sales_invoice_voided_by       FOREIGN KEY (voided_by)    REFERENCES app_users (id),
    CONSTRAINT chk_sales_invoice_doc_type       CHECK (document_type IN ('INVOICE')),
    CONSTRAINT chk_sales_invoice_status         CHECK (status IN ('DRAFT','FINALISED','VOID')),
    CONSTRAINT chk_sales_invoice_number_when_finalised
        CHECK ((status = 'DRAFT' AND invoice_number IS NULL)
            OR (status IN ('FINALISED','VOID') AND invoice_number IS NOT NULL)),
    CONSTRAINT chk_sales_invoice_doc_discount
        CHECK (doc_discount_percent IS NULL OR (doc_discount_percent >= 0 AND doc_discount_percent <= 100)),
    CONSTRAINT chk_sales_invoice_totals_nonneg
        CHECK (net_total_amount >= 0 AND vat_total_amount >= 0 AND gross_total_amount >= 0)
);

-- (5) sales_invoice_lines (child)
CREATE TABLE sales_invoice_lines (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                  VARCHAR(26)     NOT NULL,
    invoice_id           BIGINT          NOT NULL,
    company_id           BIGINT          NOT NULL,
    branch_id            BIGINT          NOT NULL,
