    product_id           BIGINT          NOT NULL,
    product_code         VARCHAR(20)     NOT NULL,
    product_name         VARCHAR(200)    NOT NULL,
    unit_id              BIGINT          NOT NULL,
    unit_name            VARCHAR(60)     NOT NULL,
    quantity             NUMERIC(19,6)   NOT NULL,
    qty_in_base          NUMERIC(19,6)   NOT NULL,
    list_price_amount    NUMERIC(19,4)   NOT NULL,
    unit_price_amount    NUMERIC(19,4)   NOT NULL,
    price_overridden     BOOLEAN         NOT NULL DEFAULT false,
    overridden_by        BIGINT,
    line_discount_amount  NUMERIC(19,4),
    line_discount_percent NUMERIC(9,4),
    vat_status           VARCHAR(20)     NOT NULL,
    vat_rate             NUMERIC(9,4)    NOT NULL,
    net_amount           NUMERIC(19,4)   NOT NULL DEFAULT 0,
    vat_amount           NUMERIC(19,4)   NOT NULL DEFAULT 0,
    gross_amount         NUMERIC(19,4)   NOT NULL DEFAULT 0,
    currency             VARCHAR(3)      NOT NULL,
    created_at           TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by           BIGINT,
    updated_at           TIMESTAMPTZ,
    updated_by           BIGINT,
    CONSTRAINT uq_sales_invoice_line_uid     UNIQUE (uid),
    CONSTRAINT uq_sales_invoice_line_no      UNIQUE (invoice_id, line_no),
    CONSTRAINT fk_sales_invoice_line_invoice FOREIGN KEY (invoice_id)    REFERENCES sales_invoices (id),
    CONSTRAINT fk_sales_invoice_line_product FOREIGN KEY (product_id)    REFERENCES products (id),
    CONSTRAINT fk_sales_invoice_line_unit    FOREIGN KEY (unit_id)       REFERENCES units_of_measure (id),
    CONSTRAINT fk_sales_invoice_line_overridden_by FOREIGN KEY (overridden_by) REFERENCES app_users (id),
    CONSTRAINT fk_sales_invoice_line_company FOREIGN KEY (company_id)    REFERENCES companies (id),
    CONSTRAINT fk_sales_invoice_line_branch  FOREIGN KEY (branch_id)     REFERENCES branches (id),
    CONSTRAINT chk_sales_invoice_line_vat_status CHECK (vat_status IN ('STANDARD','ZERO_RATED','EXEMPT')),
    CONSTRAINT chk_sales_invoice_line_qty        CHECK (quantity > 0 AND qty_in_base > 0),
    CONSTRAINT chk_sales_invoice_line_amounts    CHECK (net_amount >= 0 AND vat_amount >= 0 AND gross_amount >= 0),
    CONSTRAINT chk_sales_invoice_line_disc_pct
        CHECK (line_discount_percent IS NULL OR (line_discount_percent >= 0 AND line_discount_percent <= 100))
);

-- (6) sales_invoice_payments (child)
CREATE TABLE sales_invoice_payments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid           VARCHAR(26)     NOT NULL,
    invoice_id    BIGINT          NOT NULL,
    company_id    BIGINT          NOT NULL,
    branch_id     BIGINT          NOT NULL,
    tender_type   VARCHAR(20)     NOT NULL,
    amount        NUMERIC(19,4)   NOT NULL,
    currency      VARCHAR(3)      NOT NULL,
    change_amount NUMERIC(19,4),
    reference     VARCHAR(80),
    received_at   TIMESTAMPTZ     NOT NULL DEFAULT now(),
    received_by   BIGINT          NOT NULL,
    created_at    TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by    BIGINT,
    CONSTRAINT uq_sales_invoice_payment_uid     UNIQUE (uid),
    CONSTRAINT fk_sales_invoice_payment_invoice FOREIGN KEY (invoice_id) REFERENCES sales_invoices (id),
    CONSTRAINT fk_sales_invoice_payment_by      FOREIGN KEY (received_by) REFERENCES app_users (id),
    CONSTRAINT fk_sales_invoice_payment_company FOREIGN KEY (company_id) REFERENCES companies (id),
    CONSTRAINT fk_sales_invoice_payment_branch  FOREIGN KEY (branch_id)  REFERENCES branches (id),
    CONSTRAINT chk_sales_invoice_payment_tender CHECK (tender_type IN ('CASH','MOBILE_MONEY')),
    CONSTRAINT chk_sales_invoice_payment_amount CHECK (amount > 0),
    CONSTRAINT chk_sales_invoice_payment_change CHECK (change_amount IS NULL OR change_amount >= 0)
);

