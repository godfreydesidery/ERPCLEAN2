-- ============================================================================
-- (9) Default cash/bank account seed per company (D-10/D-13)
-- Each existing company gets one default CASH account whose gl_account_id is
-- the company's gl_configs CASH-mapped account (so unchanged AR/AP callers
-- keep posting to the same GL account they always did — zero behaviour change).
-- deterministic seed-uid: 'CBSD' + lpad(company_id,6,'0') + 'CASH'
-- ============================================================================
INSERT INTO cash_bank_accounts (
    uid, company_id, code, name, account_type, currency,
    gl_account_id, is_default, active, version, created_at
)
SELECT
    'CBSD' || lpad(c.id::text, 6, '0') || 'CASH' AS uid,
    c.id                                           AS company_id,
    'CB-0001'                                      AS code,
    'Default Cash Account'                         AS name,
    'CASH'                                         AS account_type,
    COALESCE(c.base_currency, 'TZS')               AS currency,
    coa.id                                         AS gl_account_id,
    TRUE                                           AS is_default,
    TRUE                                           AS active,
    0                                              AS version,
    now()                                          AS created_at
FROM companies c
JOIN gl_configs gc  ON gc.company_id = c.id AND gc.config_key = 'CASH'
JOIN chart_of_accounts coa ON coa.id = gc.account_id
ON CONFLICT (company_id, code) DO NOTHING;
