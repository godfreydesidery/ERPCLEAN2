-- V13 — Cash & Bank module (ADR-0016): cash_bank_accounts, bank_reconciliations,
-- cash_transactions, cash_transfers, cheques;
-- AR/AP additive nullable ALTER (cash_bank_account_id);
-- journal source-type CHECK widen (CASH_TRANSFER, CASH_DIRECT);
-- default cash/bank account seed per company (gl_configs.CASH → default account);
-- permissions seed + ORG_ADMIN grant.
-- Additive only. V1–V12 are FROZEN.
-- Order per ADR-0016 D-14:
--   cash_bank_accounts → bank_reconciliations → cash_transactions →
--   cash_transfers → cheques → indexes →
--   AR/AP additive ALTERs → journal source-type CHECK widen →
--   default cash/bank account seed → permission seed.

-- ============================================================================
-- (1) cash_bank_accounts — the money locations (master, per company)
-- ============================================================================
CREATE TABLE cash_bank_accounts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                 VARCHAR(26)     NOT NULL,
    company_id          BIGINT          NOT NULL,
    branch_id           BIGINT,
    code                VARCHAR(30)     NOT NULL,
    name                VARCHAR(120)    NOT NULL,
    account_type        VARCHAR(10)     NOT NULL,
    bank_name           VARCHAR(120),
    bank_account_no     VARCHAR(60),
    bank_branch         VARCHAR(120),
    -- P2: bank-identifier detail (BANK accounts), all nullable
    iban                VARCHAR(34),                          -- P2: International Bank Account Number
    swift               VARCHAR(11),                          -- P2: SWIFT code
    bic                 VARCHAR(11),                          -- P2: Bank Identifier Code
    sort_code           VARCHAR(20),                          -- P2: domestic sort / routing code
    -- P2: treasury limits + cached reconciliation figures, all nullable
    overdraft_limit         NUMERIC(19,4),                    -- P2: agreed overdraft limit
    minimum_balance         NUMERIC(19,4),                    -- P2: minimum-balance floor
    last_reconciled_date    DATE,                             -- P2: date of last completed reconciliation
    last_reconciled_balance NUMERIC(19,4),                    -- P2: balance at last reconciliation
    currency            VARCHAR(3)      NOT NULL,
    gl_account_id       BIGINT          NOT NULL,
    is_default          BOOLEAN         NOT NULL DEFAULT FALSE,
    active              BOOLEAN         NOT NULL DEFAULT TRUE,
    version             BIGINT          NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ,
    updated_by          BIGINT,

    CONSTRAINT uq_cash_bank_account_uid             UNIQUE (uid),
    CONSTRAINT uq_cash_bank_account_company_code    UNIQUE (company_id, code),
    CONSTRAINT uq_cash_bank_account_gl              UNIQUE (company_id, gl_account_id),
    CONSTRAINT fk_cash_bank_account_company         FOREIGN KEY (company_id)    REFERENCES companies (id),
    CONSTRAINT fk_cash_bank_account_branch          FOREIGN KEY (branch_id)     REFERENCES branches (id),
    CONSTRAINT fk_cash_bank_account_gl_account      FOREIGN KEY (gl_account_id) REFERENCES chart_of_accounts (id),
    CONSTRAINT chk_cash_bank_account_type           CHECK (account_type IN ('CASH','BANK')),
    CONSTRAINT chk_cash_bank_account_bank_details   CHECK (
        (account_type = 'BANK')
        OR (bank_name IS NULL AND bank_account_no IS NULL AND bank_branch IS NULL))
);

-- Partial unique: at most one default per company (BR-CASH-09)
CREATE UNIQUE INDEX uq_cash_bank_account_default
    ON cash_bank_accounts (company_id)
    WHERE is_default = TRUE;

-- ============================================================================
-- (2) bank_reconciliations — before cash_transactions (FK from transactions → recon)
-- ============================================================================
CREATE TABLE bank_reconciliations (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                         VARCHAR(26)     NOT NULL,
    company_id                  BIGINT          NOT NULL,
    branch_id                   BIGINT,
    cash_bank_account_id        BIGINT          NOT NULL,
    reconciliation_number       VARCHAR(30)     NOT NULL,
    statement_date              DATE            NOT NULL,
    statement_opening_balance   NUMERIC(19,4),
    statement_closing_balance   NUMERIC(19,4)   NOT NULL,
    cleared_book_balance        NUMERIC(19,4),
    unreconciled_amount         NUMERIC(19,4),
    status                      VARCHAR(10)     NOT NULL DEFAULT 'DRAFT',
    reconciled_by               BIGINT,
    completed_at                TIMESTAMPTZ,
    version                     BIGINT          NOT NULL DEFAULT 0,
    created_at                  TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by                  BIGINT,
    updated_at                  TIMESTAMPTZ,
    updated_by                  BIGINT,

    CONSTRAINT uq_bank_reconciliation_uid               UNIQUE (uid),
    CONSTRAINT uq_bank_reconciliation_company_number    UNIQUE (company_id, reconciliation_number),
    CONSTRAINT fk_bank_reconciliation_company           FOREIGN KEY (company_id)           REFERENCES companies (id),
    CONSTRAINT fk_bank_reconciliation_branch            FOREIGN KEY (branch_id)            REFERENCES branches (id),
    CONSTRAINT fk_bank_reconciliation_account           FOREIGN KEY (cash_bank_account_id) REFERENCES cash_bank_accounts (id),
    CONSTRAINT chk_bank_reconciliation_status           CHECK (status IN ('DRAFT','COMPLETED'))
);

-- ============================================================================
-- (3) cash_transactions — the cash/bank ledger (append-only)
-- ============================================================================
CREATE TABLE cash_transactions (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                         VARCHAR(26)     NOT NULL,
    company_id                  BIGINT          NOT NULL,
    branch_id                   BIGINT,
    cash_bank_account_id        BIGINT          NOT NULL,
    txn_number                  VARCHAR(30)     NOT NULL,
    txn_date                    DATE            NOT NULL,
    value_date                  DATE,                         -- P2: bank value date (when funds cleared), nullable
    cheque_id                   BIGINT,                       -- P2: linked cheque (soft ref → cheques.id; cheques created later in V13), nullable
    direction                   VARCHAR(3)      NOT NULL,
    amount                      NUMERIC(19,4)   NOT NULL,
    currency                    VARCHAR(3)      NOT NULL,
    txn_type                    VARCHAR(20)     NOT NULL,
    source_ref                  VARCHAR(26),
    counter_gl_account_id       BIGINT,
    journal_entry_ref           VARCHAR(26),
    cleared                     BOOLEAN         NOT NULL DEFAULT FALSE,
    cleared_in_reconciliation_id BIGINT,
    memo                        VARCHAR(255),
    version                     BIGINT          NOT NULL DEFAULT 0,
    created_at                  TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by                  BIGINT,
    updated_at                  TIMESTAMPTZ,
    updated_by                  BIGINT,

    CONSTRAINT uq_cash_transaction_uid              UNIQUE (uid),
    CONSTRAINT uq_cash_transaction_company_number   UNIQUE (company_id, txn_number),
    CONSTRAINT fk_cash_transaction_company          FOREIGN KEY (company_id)           REFERENCES companies (id),
    CONSTRAINT fk_cash_transaction_branch           FOREIGN KEY (branch_id)            REFERENCES branches (id),
    CONSTRAINT fk_cash_transaction_account          FOREIGN KEY (cash_bank_account_id) REFERENCES cash_bank_accounts (id),
    CONSTRAINT fk_cash_transaction_counter_gl       FOREIGN KEY (counter_gl_account_id) REFERENCES chart_of_accounts (id),
    CONSTRAINT fk_cash_transaction_reconciliation   FOREIGN KEY (cleared_in_reconciliation_id) REFERENCES bank_reconciliations (id),
    CONSTRAINT chk_cash_transaction_direction       CHECK (direction IN ('IN','OUT')),
    CONSTRAINT chk_cash_transaction_type            CHECK (txn_type IN (
        'AR_RECEIPT','AP_PAYMENT','TRANSFER_IN','TRANSFER_OUT','DIRECT_ENTRY')),
    CONSTRAINT chk_cash_transaction_amount          CHECK (amount > 0),
    CONSTRAINT chk_cash_transaction_counter_gl      CHECK (
        (txn_type = 'DIRECT_ENTRY' AND counter_gl_account_id IS NOT NULL)
        OR (txn_type <> 'DIRECT_ENTRY')),
    CONSTRAINT chk_cash_transaction_cleared         CHECK (
        (cleared = FALSE AND cleared_in_reconciliation_id IS NULL)
        OR (cleared = TRUE AND cleared_in_reconciliation_id IS NOT NULL))
);

-- ============================================================================
-- (4) cash_transfers — the inter-account transfer header (CBT-####)
-- ============================================================================
CREATE TABLE cash_transfers (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                     VARCHAR(26)     NOT NULL,
    company_id              BIGINT          NOT NULL,
    branch_id               BIGINT,
    transfer_number         VARCHAR(30)     NOT NULL,
    source_account_id       BIGINT          NOT NULL,
    destination_account_id  BIGINT          NOT NULL,
    transfer_date           DATE            NOT NULL,
    amount                  NUMERIC(19,4)   NOT NULL,
    currency                VARCHAR(3)      NOT NULL,
    reference               VARCHAR(255),
    out_txn_id              BIGINT          NOT NULL,
    in_txn_id               BIGINT          NOT NULL,
    journal_entry_ref       VARCHAR(26),
    version                 BIGINT          NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by              BIGINT,
    updated_at              TIMESTAMPTZ,
    updated_by              BIGINT,

    CONSTRAINT uq_cash_transfer_uid             UNIQUE (uid),
    CONSTRAINT uq_cash_transfer_company_number  UNIQUE (company_id, transfer_number),
    CONSTRAINT fk_cash_transfer_company         FOREIGN KEY (company_id)             REFERENCES companies (id),
    CONSTRAINT fk_cash_transfer_branch          FOREIGN KEY (branch_id)              REFERENCES branches (id),
    CONSTRAINT fk_cash_transfer_source          FOREIGN KEY (source_account_id)      REFERENCES cash_bank_accounts (id),
    CONSTRAINT fk_cash_transfer_destination     FOREIGN KEY (destination_account_id) REFERENCES cash_bank_accounts (id),
    CONSTRAINT fk_cash_transfer_out_txn         FOREIGN KEY (out_txn_id)             REFERENCES cash_transactions (id),
    CONSTRAINT fk_cash_transfer_in_txn          FOREIGN KEY (in_txn_id)              REFERENCES cash_transactions (id),
    CONSTRAINT chk_cash_transfer_amount         CHECK (amount > 0),
    CONSTRAINT chk_cash_transfer_distinct       CHECK (source_account_id <> destination_account_id)
);

-- ============================================================================
-- (5) cheques — the cheque register (BANK accounts only)
-- D-9: bidirectional — OUTBOUND (AP payments) or INBOUND (AR receipts).
-- ============================================================================
CREATE TABLE cheques (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                     VARCHAR(26)     NOT NULL,
    company_id              BIGINT          NOT NULL,
    branch_id               BIGINT,
    cash_bank_account_id    BIGINT          NOT NULL,
    cheque_number           VARCHAR(40)     NOT NULL,
    payee                   VARCHAR(160)    NOT NULL,
    amount                  NUMERIC(19,4)   NOT NULL,
    currency                VARCHAR(3)      NOT NULL,
    issue_date              DATE            NOT NULL,
    value_date              DATE            NOT NULL,
    status                  VARCHAR(12)     NOT NULL DEFAULT 'ISSUED',
    ap_payment_uid          VARCHAR(26),
    cash_transaction_uid    VARCHAR(26),
    cleared_at              TIMESTAMPTZ,
    cancelled_at            TIMESTAMPTZ,
    -- D-9: bidirectional cheque fields (ADR-0040 D-9)
    direction               VARCHAR(8)      NOT NULL DEFAULT 'OUTBOUND',  -- OUTBOUND|INBOUND
    ar_receipt_uid          VARCHAR(26),        -- scalar ref for INBOUND cheques (no FK — cross-module)
    deposited_at            TIMESTAMPTZ,        -- when the inbound cheque was deposited to the bank
    bounced_at              TIMESTAMPTZ,        -- when the cheque bounced
    bounce_reason           VARCHAR(160),       -- free-text reason from the bank
    represent_count         SMALLINT        NOT NULL DEFAULT 0,  -- how many times re-presented after bounce
    version                 BIGINT          NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by              BIGINT,
    updated_at              TIMESTAMPTZ,
    updated_by              BIGINT,

    CONSTRAINT uq_cheque_uid                UNIQUE (uid),
    CONSTRAINT uq_cheque_bank_number        UNIQUE (cash_bank_account_id, cheque_number),
    CONSTRAINT fk_cheque_company            FOREIGN KEY (company_id)           REFERENCES companies (id),
    CONSTRAINT fk_cheque_branch             FOREIGN KEY (branch_id)            REFERENCES branches (id),
    CONSTRAINT fk_cheque_account            FOREIGN KEY (cash_bank_account_id) REFERENCES cash_bank_accounts (id),
    CONSTRAINT chk_cheque_status            CHECK (status IN ('ISSUED','CLEARED','CANCELLED','DEPOSITED','BOUNCED')),
    CONSTRAINT chk_cheque_amount            CHECK (amount > 0),
    CONSTRAINT chk_cheque_dates             CHECK (value_date >= issue_date),
    CONSTRAINT chk_cheque_direction         CHECK (direction IN ('OUTBOUND','INBOUND')),
    CONSTRAINT chk_cheque_inbound_link      CHECK (
        (direction = 'OUTBOUND' AND ar_receipt_uid IS NULL)
        OR direction = 'INBOUND')
);

